def bullet(text: str):
    return para("• " + text, S["body"])


def table(rows: list[list[str]], widths: list[float]) -> Table:
    shaped = []
    for row_index, row in enumerate(rows):
        style = S["table_head"] if row_index == 0 else S["table"]
        shaped.append([para(cell, style) for cell in row])
    t = Table(shaped, colWidths=widths)
    t.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), NAVY),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, PALE]),
        ("BOX", (0, 0), (-1, -1), 0.5, colors.HexColor("#D9E7E6")),
        ("INNERGRID", (0, 0), (-1, -1), 0.35, colors.HexColor("#D9E7E6")),
        ("VALIGN", (0, 0), (-1, -1), "TOP"),
        ("LEFTPADDING", (0, 0), (-1, -1), 6),
        ("RIGHTPADDING", (0, 0), (-1, -1), 6),
        ("TOPPADDING", (0, 0), (-1, -1), 6),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
    ]))
    return t


